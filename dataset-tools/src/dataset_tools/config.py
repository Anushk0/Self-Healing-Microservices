# --- Fault domain knowledge (mirrors the actual Java fault mechanisms - see each service's
# fault package). Used to label root cause / symptom and to drive the synthetic model. ---

FAULT_TYPES = ["auth-key-error", "memory-leak", "db-lock", "notification-latency"]

FAULT_SERVICE_MAP = {
    # Verified against real Week 5 telemetry (not assumed): auth-service's own
    # /api/auth/validate endpoint always returns HTTP 200 (it reports {"valid": false} in the
    # body, not an HTTP error), so auth-service's own http_server_requests_error_count never
    # moves during this fault. The HTTP-level symptom (401s) is generated by payment-service's
    # GlobalExceptionHandler in response to the failed validation - confirmed live:
    # payment-service's http_server_requests_error_count rose 0->5 across 5 failed probes while
    # auth-service's stayed at 0.0 for the entire fault window. So the root cause is
    # auth-service's key state, but the metric-visible symptom is on payment-service - a second,
    # less obvious cross-service case alongside notification-latency's.
    "auth-key-error": {"root_cause_service": "auth-service", "symptom_service": "payment-service"},
    "memory-leak": {"root_cause_service": "payment-service", "symptom_service": "payment-service"},
    "db-lock": {"root_cause_service": "ledger-service", "symptom_service": "ledger-service"},
    # The other deliberately cross-service case: root cause is notification-service, but the
    # symptom (timeout) is observed on payment-service - this is the scenario CLAUDE.md calls
    # out explicitly as the case the eventual RCA agent must get right.
    "notification-latency": {"root_cause_service": "notification-service", "symptom_service": "payment-service"},
}

